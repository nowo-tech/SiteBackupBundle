/**
 * PP-M1 / PP-M2 / PP-M3: decoded binary logs reduced to (or checked against) one schema, event by event, failing
 * closed on anything that cannot be attributed. Fixtures follow the shape of `mysqlbinlog --skip-gtids` 9.7 output
 * (audit PP scenarios B and C).
 */
final class BinlogSchemaFilterTest extends TestCase
{
    private string $dir;

    private int $files = 0;

    protected function setUp(): void
    {
        $this->dir = EngineFixtures::tempDir('sbb-filter-');
    }

    protected function tearDown(): void
    {
        (new Filesystem())->remove($this->dir);
    }

