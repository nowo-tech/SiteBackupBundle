    #[DataProvider('statements')]
    public function testClassifier(string $statement, ?string $defaultDb, string $expected): void
    {
        self::assertSame($expected, C::classify($statement, $defaultDb, 'app')[0]);
    }

    public function testFilterKeepsOnlyTheSchemaAndNormalisesTheDefaultDatabase(): void
    {
        $input = $this->decoded([
            $this->query('2765', '10:51:16', 'app', ['BEGIN']),
            $this->rows('2800', '10:51:16', 'app', 'pitr', 'APPROWS'),
            $this->xid('2900', '10:51:16'),
            // Scenario B: DROP of another schema's table from an app session.
            $this->query('3000', '10:51:16', 'app', ['DROP TABLE `other`.`victim` /* generated by server */']),
            // Another tenant's rows and an account statement.
            $this->query('3100', '10:51:16', 'other', ['BEGIN']),
            $this->rows('3150', '10:51:16', 'other', 'victim', 'OTHERROWS'),
            $this->xid('3200', '10:51:16'),
            $this->query('3300', '10:51:17', null, ["CREATE USER 'x'@'%' IDENTIFIED BY 'secret-hash'"]),
            // Scenario C: DDL on app without a default database (a DBA session).
            $this->query('3400', '10:51:18', null, ['ALTER TABLE app.pitr ADD COLUMN w INT NOT NULL DEFAULT 7']),
            $this->rows('3500', '10:51:19', 'app', 'pitr', 'APPROWS2'),
        ]);

        $out    = $this->dir . '/out.sql';
        $result = BinlogSchemaFilter::run([$input], $out, 'app', BinlogSchemaFilter::FILTER);
        $sql    = (string) file_get_contents($out);

        self::assertTrue($result->isClean(), implode('; ', $result->problems));
        self::assertSame(3, $result->droppedEvents);
        self::assertStringContainsString('APPROWS', $sql);
        self::assertStringContainsString('APPROWS2', $sql);
        self::assertStringContainsString('ALTER TABLE app.pitr ADD COLUMN w', $sql);
        self::assertStringNotContainsString('OTHERROWS', $sql);
        self::assertStringNotContainsString('victim', $sql);
        self::assertStringNotContainsString('CREATE USER', $sql);
        self::assertStringNotContainsString('use `other`', $sql);
        self::assertStringContainsString("use `app`/*!*/;\nSET TIMESTAMP", $sql);
        self::assertStringContainsString('# End of log file', $sql);
        self::assertSame('2026-11-14 10:51:16', $result->firstEventAt?->format('Y-m-d H:i:s'));
        self::assertSame('2026-11-14 10:51:19', $result->lastEventAt?->format('Y-m-d H:i:s'));

        // The same input in check mode (restore of a raw capture): every foreign event is a refusal.
        $check = BinlogSchemaFilter::run([$input], $this->dir . '/check.sql', 'app', BinlogSchemaFilter::CHECK);
        self::assertSame(3, $check->problemCount);
        self::assertStringContainsString('DROP TABLE on another database', implode(' ', $check->problems));
        self::assertStringNotContainsString('victim', implode(' ', $check->problems));

        // The filtered output passes the check, and a cut at 10:51:18 ends before the ALTER, rolling back.
        $again = BinlogSchemaFilter::run([$out], $this->dir . '/again.sql', 'app', BinlogSchemaFilter::CHECK, new DateTimeImmutable('2026-11-14 10:51:18 UTC'));
        self::assertTrue($again->isClean());
        self::assertTrue($again->cut);
        $cut = (string) file_get_contents($this->dir . '/again.sql');
        self::assertStringNotContainsString('ALTER TABLE', $cut);
        self::assertStringEndsWith("ROLLBACK /* nowo-site-backup: --until */\n/*!*/;\n", $cut);
    }

    public function testUnattributableEventsFailClosed(): void
    {
        $cases = [
            'mixed rows'        => [$this->rows('10', '10:00:00', 'app', 't', 'X', 'other')],
            'unknown statement' => [$this->query('10', '10:00:00', 'app', ['HANDLER t OPEN'])],
            'drop own schema'   => [$this->query('10', '10:00:00', 'app', ['DROP DATABASE app'])],
            'unknown event'     => [$this->event('10', '10:00:00', 'Execute_load_query', "LOAD DATA INFILE 'x' INTO TABLE t\n/*!*/;\n")],
            'rows without map'  => [$this->event('10', '10:00:00', 'Write_rows: table id 1 flags: STMT_END_F', "\nBINLOG '\nX\n'/*!*/;\n")],
            'interrupted group' => [$this->event('10', '10:00:00', 'Table_map: `app`.`t` mapped to number 1', ''), $this->xid('20', '10:00:00')],
            'open group at end' => [$this->event('10', '10:00:00', 'Table_map: `app`.`t` mapped to number 1', '')],
        ];
        foreach ($cases as $case => $events) {
            $result = BinlogSchemaFilter::run([$this->decoded($events)], $this->dir . '/' . $this->files++ . '.out', 'app', BinlogSchemaFilter::FILTER);
            self::assertFalse($result->isClean(), $case);
        }

        // Many problems are capped.
        $many = [];
        for ($i = 0; $i < 25; ++$i) {
            $many[] = $this->query((string) (100 + $i), '10:00:00', 'app', ['DROP DATABASE app']);
        }
        $result = BinlogSchemaFilter::run([$this->decoded($many)], $this->dir . '/many.out', 'app', BinlogSchemaFilter::FILTER);
        self::assertSame(25, $result->problemCount);
        self::assertCount(20, $result->problems);
    }

    public function testIoErrors(): void
    {
        try {
            BinlogSchemaFilter::run([$this->dir . '/missing'], $this->dir . '/x.out', 'app', BinlogSchemaFilter::FILTER);
            self::fail('a missing input was accepted');
        } catch (RuntimeException) {
        }
        file_put_contents($this->dir . '/exists', '');
        $this->expectException(RuntimeException::class);
        BinlogSchemaFilter::run([], $this->dir . '/exists', 'app', BinlogSchemaFilter::FILTER);
    }

    /**
     * @param list<string> $events
     */
    private function decoded(array $events): string
    {
        $path = $this->dir . '/in-' . $this->files++ . '.sql';
        file_put_contents($path, "/*!50530 SET @@SESSION.PSEUDO_SLAVE_MODE=1*/;\nDELIMITER /*!*/;\n"
            . $this->event('4', '10:50:00', 'Start: binlog v 4, server v 9.7.2', "BINLOG '\nFDE\n'/*!*/;\n")
            . implode('', $events)
            . $this->event('9999', '10:52:00', 'Rotate to binlog.000005  pos: 4', '')
            . "DELIMITER ;\n# End of log file\n/*!50530 SET @@SESSION.PSEUDO_SLAVE_MODE=0*/;\n");

        return $path;
    }

    /**
     * @param list<string> $statements
     */
    private function query(string $at, string $time, ?string $db, array $statements): string
    {
        $content = $db !== null ? 'use `' . $db . "`/*!*/;\n" : '';
        $content .= "SET TIMESTAMP=1794653476/*!*/;\nSET @@session.pseudo_thread_id=29/*!*/;\n/*!\\C latin1 *//*!*/;\n";
        foreach ($statements as $statement) {
            $content .= $statement . "\n/*!*/;\n";
        }

        return $this->event($at, $time, "Query\tthread_id=29\texec_time=0\terror_code=0", $content);
    }

    private function rows(string $at, string $time, string $db, string $table, string $payload, ?string $secondDb = null): string
    {
        $maps = $this->event($at, $time, 'Table_map: `' . $db . '`.`' . $table . '` mapped to number 150', '');
        if ($secondDb !== null) {
            $maps .= $this->event($at . '1', $time, 'Table_map: `' . $secondDb . '`.`x` mapped to number 151', '');
        }

        return $maps . $this->event($at . '2', $time, 'Write_rows: table id 150 flags: STMT_END_F', "\nBINLOG '\n" . $payload . "\n'/*!*/;\n");
    }

    private function xid(string $at, string $time): string
    {
        return $this->event($at, $time, 'Xid = 228', "COMMIT/*!*/;\n");
    }

    private function event(string $at, string $time, string $type, string $content): string
    {
        return '# at ' . $at . "\n#261114 " . $time . ' server id 1  end_log_pos 1 CRC32 0x1 ' . "\t" . $type . "\n" . $content;
    }
}
